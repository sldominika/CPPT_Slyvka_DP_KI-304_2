package KI_304.Slyvka.Lab3;

/**
 * Інтерфейс для зброї, що використовує воду.
 * Описує базові операції резервуара.
 */
public interface WaterWeapon {

    /**
     * Додати воду в резервуар.
     *
     * @param units одиниць води
     */
    void refillWater(int units);

    /**
     * Повернути поточний рівень води.
     *
     * @return одиниці води
     */
    int getWaterLevel();

    /**
     * Виконати розпилення/вистріл водою.
     * Повинно змінювати рівень води та логувати дію.
     */
    void spray();
}
